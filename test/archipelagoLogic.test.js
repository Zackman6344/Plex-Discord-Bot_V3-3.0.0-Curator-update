// Finding what the logic worker needs, talking to it, and keeping exactly one of it running.
//
// None of this fails loudly. A seed zip that is not found or a worker that dies ends in
// `!ap next` quietly answering from sphere 1; a reply taken for another request's ends in it
// quietly answering wrong; a second startup costs another half gigabyte and another minute of
// Python. The bot's copy of a seed's yamls is as quiet: one yaml missing, edited or extra and the
// worker rebuilds some other seed, and every slot it touches answers from sphere 1. So each step is
// pinned down on its own: the disk lookups and the copy against temp folders laid out like an
// Archipelago install, LogicWorker against test/helpers/fakeLogicWorker.js (which speaks the real
// worker's JSON-lines protocol), and acquire() with its _deps pointed at that fake.
//
// Every fake appends its pid to a file, and afterEach waits for all of them to be gone, so a test
// that leaves a process behind fails there rather than slowing down the rest of the suite.
//
// Every test gets its own PLEXBOT_AP_SEEDS_DIR: copies are kept by seed name, which most tests
// share, and a run outside `node --test` has nothing else keeping a copy out of the bot's own data
// folder.

const test = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const config = require('../config/config.js');
const logger = require('../helpers/logger.js');
const logic = require('../helpers/archipelagoLogic.js');

const FAKE = path.join(__dirname, 'helpers', 'fakeLogicWorker.js');
const SPAWNS = path.join(os.tmpdir(), `plexbot-test-logic-spawns-${process.pid}.txt`);
process.env.FAKE_LOGIC_WORKER_SPAWNS = SPAWNS;

const REAL_DEPS = { ...logic._deps };
const REAL_INSTALL_DIR = config.archipelagoInstallDir;
const REAL_PYTHON = config.archipelagoPython;
const REAL_SEEDS_DIR = process.env.PLEXBOT_AP_SEEDS_DIR;

// Real names and numbers are twenty digits; these have the same shape.
const SEED_NAME = '51632394463281032748';
const SEED = '31755677627148142336';
const LOG = `Generate_${SEED}_2026_11_09_15_30_58.txt`;

// The yamls a run rolled, one log line per player. Archipelago rolls them in case-blind name order,
// which puts Raft before REPO where a plain sort would not, and names a yaml holding two players
// (ZackLL1Words.yaml) once for each.
const YAMLS = ['BeansClover.yaml', 'MarysEdge.yaml', 'ZackLL1Raft.yaml', 'ZackLL1REPO.yaml',
    'ZackLL1Words.yaml', 'ZackLL1Words.yaml', 'ZackLL1Zelda.yaml'];
const YAML_FILES = ['BeansClover.yaml', 'MarysEdge.yaml', 'ZackLL1Raft.yaml', 'ZackLL1REPO.yaml',
    'ZackLL1Words.yaml', 'ZackLL1Zelda.yaml'];

// A run that ended an hour ago, rolled from yamls last saved ten minutes before that. Whole seconds,
// so a time set on a file reads back exactly.
const GENERATED_AT = new Date(Math.floor(Date.now() / 1000) * 1000 - 3600000);
const SAVED_AT = new Date(GENERATED_AT.getTime() - 600000);

const sleep = (ms) => new Promise(resolve => setTimeout(resolve, ms));

// Captured rather than printed: several cases fail on purpose, and for a startup the log is the
// only place some of what happened shows.
const logged = [];
const realLog = { info: logger.info, warn: logger.warn };
logger.info = (...parts) => logged.push(parts.join(' '));
logger.warn = (...parts) => logged.push(parts.join(' '));

const tempDirs = [];
function tempDir() {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'plexbot-test-logic-'));
    tempDirs.push(dir);
    return dir;
}

function yamlNames(count) {
    return Array.from({ length: count }, (_, i) => `Player${i + 1}.yaml`);
}

/** The head of a Generate log as Archipelago 0.6.8 writes it: a line per player, then the seed. */
function generateLog(seedName, seed, yamls = yamlNames(3)) {
    const at = '[root at 2026-11-09 15:30:58,882]: ';
    return [
        `\uFEFF${at}Archipelago (0.6.8) logging initialized on Windows-11-10.0.26200-SP0 process 23368 running Python 3.13.15 (frozen)`,
        ...yamls.map((file, i) => `${at}P${i + 1} Weights: ${file} >> YAML generated by Archipelago 0.6.8.`),
        `${at}Generating for ${yamls.length} players, ${seedName} Seed ${seed} with plando: connections, texts, bosses`,
        `${at}Creating World.`,
        ''
    ].join('\r\n');
}

function writeYamls(folder, names) {
    fs.mkdirSync(folder, { recursive: true });
    for (const name of names) {
        const file = path.join(folder, name);
        fs.writeFileSync(file, `name: ${path.parse(name).name}\r\ngame: Clique\r\n`);
        fs.utimesSync(file, SAVED_AT, SAVED_AT);
    }
}

/**
 * A folder laid out like an Archipelago install, with only the parts asked for. Logs carry the time
 * the run ended and yamls a time before it, as a real run leaves them.
 */
function fakeInstall({ dll = 'python313.dll', logs = null, multidataFor = null, players = null, hostYaml = null } = {}) {
    const dir = tempDir();
    if (dll) fs.writeFileSync(path.join(dir, dll), '');
    if (hostYaml !== null) fs.writeFileSync(path.join(dir, 'host.yaml'), hostYaml);
    if (players) writeYamls(path.join(dir, 'Players'), players);
    if (logs) {
        fs.mkdirSync(path.join(dir, 'logs'));
        for (const [name, text] of Object.entries(logs)) {
            const file = path.join(dir, 'logs', name);
            fs.writeFileSync(file, text);
            fs.utimesSync(file, GENERATED_AT, GENERATED_AT);
        }
    }
    if (multidataFor) {
        fs.mkdirSync(path.join(dir, 'output'));
        fs.writeFileSync(path.join(dir, 'output', `AP_${multidataFor}.zip`), `multidata of ${multidataFor}`);
    }
    return dir;
}

/** An install that generated a seed from YAMLS, with its output zip and its yamls still in Players. */
function generatedHere({ seedName = SEED_NAME, ...parts } = {}) {
    return fakeInstall({
        logs: { [LOG]: generateLog(seedName, SEED, YAMLS) },
        multidataFor: seedName,
        players: YAML_FILES,
        ...parts
    });
}

function outputZip(apDir, seedName = SEED_NAME) {
    return path.join(apDir, 'output', `AP_${seedName}.zip`);
}

function seedsDir() {
    return process.env.PLEXBOT_AP_SEEDS_DIR;
}

function copyOf(seedName = SEED_NAME) {
    return path.join(seedsDir(), seedName);
}

const sorted = (names) => [...names].sort();

function spawnedPids() {
    try {
        return fs.readFileSync(SPAWNS, 'utf8').split('\n').filter(Boolean).map(Number);
    } catch (_) {
        return [];
    }
}

function running(pid) {
    try {
        process.kill(pid, 0);
        return true;
    } catch (err) {
        return err.code === 'EPERM';
    }
}

async function waitUntil(check, what, ms = 4000) {
    const deadline = Date.now() + ms;
    while (!check()) {
        if (Date.now() > deadline) throw new Error(`timed out waiting for ${what}`);
        await sleep(15);
    }
}

const direct = [];
function startFake(mode, extra = []) {
    const worker = new logic.LogicWorker({ command: process.execPath, args: [FAKE, '--mode', mode, ...extra], label: 'test' });
    direct.push(worker);
    return worker.start();
}

function located(apDir, seedName) {
    return {
        ok: true,
        apDir,
        seed: SEED,
        seedName,
        multidata: path.join(apDir, 'output', `AP_${seedName}.zip`),
        pythonVersion: '3.13',
        playersDir: null
    };
}

/**
 * Points acquire() at the fake in the given mode, with a stub install that always has the seed.
 * @returns {{locate: Array, python: Array}} every call the stubs saw
 */
function useFake(mode, { locate = located, python = () => ({ ok: true, command: process.execPath }) } = {}) {
    process.env.FAKE_LOGIC_WORKER_MODE = mode;
    const calls = { locate: [], python: [] };
    logic._deps.workerScript = FAKE;
    logic._deps.pythonFlags = [];
    logic._deps.locateSeed = async (apDir, seedName) => {
        calls.locate.push([apDir, seedName]);
        return locate(apDir, seedName);
    };
    logic._deps.resolvePython = async (version) => {
        calls.python.push(version);
        return python(version);
    };
    return calls;
}

test.beforeEach(() => {
    logged.length = 0;
    config.archipelagoInstallDir = 'C:\\ProgramData\\Archipelago';
    config.archipelagoPython = '';
    process.env.PLEXBOT_AP_SEEDS_DIR = tempDir();
});

test.afterEach(async () => {
    for (const worker of direct.splice(0)) worker.kill();
    logic._reset();
    Object.assign(logic._deps, REAL_DEPS);
    config.archipelagoInstallDir = REAL_INSTALL_DIR;
    config.archipelagoPython = REAL_PYTHON;
    delete process.env.FAKE_LOGIC_WORKER_MODE;
    // _reset() only asks a worker to finish, and one still starting is not killed for two
    // seconds; waiting here keeps each test's processes inside that test.
    const pids = spawnedPids();
    await waitUntil(() => pids.every(pid => !running(pid)), 'every fake worker to exit');
    fs.rmSync(SPAWNS, { force: true });
});

test.after(() => {
    Object.assign(logger, realLog);
    if (REAL_SEEDS_DIR === undefined) delete process.env.PLEXBOT_AP_SEEDS_DIR;
    else process.env.PLEXBOT_AP_SEEDS_DIR = REAL_SEEDS_DIR;
    for (const dir of tempDirs) fs.rmSync(dir, { recursive: true, force: true });
});

