// helpers/bookResource.js against the real ffmpeg-static, through helpers/partProxy.js.
//
// The bug: the book pipeline's correctness rests on ffmpeg behaviours no unit test can see. If
// `-ss` were applied in output time under atempo, a 2x resume would land at double the offset; if
// ffmpeg inherited `http_proxy` it would send the 127.0.0.1 part URL to the proxy and play
// nothing; and voice destroys playStream on a stop without ever touching the process behind it,
// so without the SIGKILL every pause, seek and speed change would leave an ffmpeg running.
//
// Harness: a 20 s sine WAV generated by ffmpeg-static into os.tmpdir(), served by a fake Plex
// that requires the X-Plex-Token header (as in test/partProxy.test.js), read by the real
// createBookResource through a real proxy. The Ogg/Opus output is captured off ffmpeg's stdout
// through the spawn seam and decoded back with ffmpeg to measure it.

const test = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const http = require('node:http');
const childProcess = require('node:child_process');

const ffmpegPath = require('ffmpeg-static');
const { createPartProxy } = require('../helpers/partProxy.js');
const { createBookResource } = require('../helpers/bookResource.js');

const TOKEN = 'synthetic-test-token-0000';
const WAV = path.join(os.tmpdir(), `plexbot-book-contract-${process.pid}.wav`);
const PART = '/library/parts/101/1700000000/file.wav';
const STALLED = '/library/parts/102/1700000000/file.wav';

let wav = null;
const held = [];

const fake = http.createServer((req, res) => {
	if (req.headers['x-plex-token'] !== TOKEN) {
		res.writeHead(401);
		res.end();
		return;
	}
	if (req.url === STALLED) {
		held.push(res);
		res.writeHead(200, { 'Content-Type': 'audio/wav', 'Content-Length': String(wav.length) });
		// Past ffmpeg's 5 s stream probe, so it has started writing audio when the body stops.
		res.write(wav.subarray(0, 2 * 1024 * 1024));
		return;
	}
	if (req.url !== PART) {
		res.writeHead(404);
		res.end();
		return;
	}
	const m = /^bytes=(\d+)-(\d*)$/.exec(req.headers.range || '');
	if (m) {
		const start = Number(m[1]);
		const end = m[2] === '' ? wav.length - 1 : Math.min(Number(m[2]), wav.length - 1);
		res.writeHead(206, {
			'Content-Type': 'audio/wav',
			'Content-Length': String(end - start + 1),
			'Content-Range': `bytes ${start}-${end}/${wav.length}`,
			'Accept-Ranges': 'bytes'
		});
		res.end(wav.subarray(start, end + 1));
		return;
	}
	res.writeHead(200, { 'Content-Type': 'audio/wav', 'Content-Length': String(wav.length), 'Accept-Ranges': 'bytes' });
	res.end(wav);
});

let proxy = null;

test.before(async () => {
	const made = childProcess.spawnSync(ffmpegPath, [
		'-y', '-nostdin', '-loglevel', 'error',
		'-f', 'lavfi', '-i', 'sine=frequency=440:sample_rate=44100:duration=20',
		'-ac', '2', WAV
	], { windowsHide: true });
	assert.strictEqual(made.status, 0, String(made.stderr));
	wav = fs.readFileSync(WAV);
	await new Promise((resolve) => fake.listen(0, '127.0.0.1', resolve));
	const fakePort = fake.address().port;
	proxy = createPartProxy({ loadConfig: () => ({ hostname: '127.0.0.1', port: fakePort, https: false, token: TOKEN }) });
	await proxy.start();
});

test.after(async () => {
	for (const res of held) res.destroy();
	await proxy.stop();
	fake.closeAllConnections();
	await new Promise((resolve) => fake.close(resolve));
	try { fs.unlinkSync(WAV); } catch {}
});

function capturingSpawn(sink) {
	return (file, args, options) => {
		const child = childProcess.spawn(file, args, options);
		sink.child = child;
		sink.args = args;
		sink.options = options;
		sink.chunks = [];
		child.stdout.on('data', (chunk) => sink.chunks.push(chunk));
		return child;
	};
}

// The way AudioPlayer consumes it: read() on 'readable'. resume() does nothing here, because
// AudioResource already holds a 'readable' listener on playStream.
function drain(stream, onFirst) {
	let first = true;
	stream.on('readable', () => {
		let got = false;
		while (stream.read() !== null) got = true;
		if (got && first && onFirst) {
			first = false;
			onFirst();
		}
	});
}

function exited(child) {
	if (child.exitCode !== null || child.signalCode !== null) return Promise.resolve();
	return new Promise((resolve) => child.once('exit', () => resolve()));
}

function within(ms, promise, what) {
	let timer;
	return Promise.race([
		promise,
		new Promise((_, reject) => { timer = setTimeout(() => reject(new Error(`${what} took over ${ms} ms`)), ms); })
	]).finally(() => clearTimeout(timer));
}

function decodedSeconds(ogg) {
	const out = childProcess.spawnSync(ffmpegPath, [
		'-nostdin', '-loglevel', 'error', '-i', 'pipe:0', '-f', 's16le', '-ac', '1', '-ar', '48000', 'pipe:1'
	], { input: ogg, maxBuffer: 64 * 1024 * 1024, windowsHide: true });
	assert.strictEqual(out.status, 0, String(out.stderr));
	return out.stdout.length / 2 / 48000;
}

test('a resume 2 s in at 2x yields 9.0 s of Ogg/Opus, with http_proxy set in the parent', async () => {
	const saved = process.env.http_proxy;
	// A dead proxy: if ffmpeg inherited it, the part would never load.
	process.env.http_proxy = 'http://127.0.0.1:9';
	const sink = {};
	let built;
	try {
		built = createBookResource({ url: proxy.urlFor(PART), startMs: 2000, speed: 2 }, { spawn: capturingSpawn(sink) });
	} finally {
		if (saved === undefined) delete process.env.http_proxy;
		else process.env.http_proxy = saved;
	}
	assert.ok(!Object.keys(sink.options.env).some((k) => k.toLowerCase() === 'http_proxy'));
	assert.ok(!sink.args.join(' ').includes(TOKEN));

	let packets = 0;
	built.resource.playStream.on('data', () => { packets++; });
	await within(10000, Promise.all([
		new Promise((resolve) => built.resource.playStream.once('end', resolve)),
		exited(sink.child)
	]), 'ffmpeg');

	const seconds = decodedSeconds(Buffer.concat(sink.chunks));
	assert.ok(Math.abs(seconds - 9.0) <= 0.05, `decoded ${seconds.toFixed(3)} s from ${packets} packets`);
	assert.ok(packets > 400, `only ${packets} Opus packets reached the demuxer`);
});

test('closing playStream SIGKILLs an ffmpeg still waiting on its input', async () => {
	const sink = {};
	const built = createBookResource({ url: proxy.urlFor(STALLED), startMs: 0, speed: 1 }, { spawn: capturingSpawn(sink) });
	await within(5000, new Promise((resolve) => drain(built.resource.playStream, resolve)), 'first audio');
	await new Promise((r) => setTimeout(r, 200));
	assert.strictEqual(sink.child.exitCode, null, 'ffmpeg ended before the stall');

	built.resource.playStream.destroy();
	await within(5000, exited(sink.child), 'ffmpeg exit after close');
	assert.strictEqual(sink.child.killed, true);
	assert.strictEqual(sink.child.exitCode === 0, false);
	built.kill();
});

test('kill is a no-op once ffmpeg has exited', async () => {
	const sink = {};
	const built = createBookResource({ url: proxy.urlFor(PART), startMs: 19000, speed: 1 }, { spawn: capturingSpawn(sink) });
	drain(built.resource.playStream);
	await within(10000, exited(sink.child), 'ffmpeg');
	const calls = [];
	sink.child.kill = (sig) => { calls.push(sig); return false; };
	built.kill();
	built.resource.playStream.destroy();
	assert.deepStrictEqual(calls, []);
});

test('a spawn failure logs and ends the stream instead of throwing', async () => {
	const lines = [];
	const original = console.error;
	console.error = (...args) => lines.push(args.join(' '));
	try {
		const built = createBookResource(
			{ url: proxy.urlFor(PART), startMs: 0, speed: 1 },
			{ ffmpegPath: path.join(os.tmpdir(), `plexbot-no-such-ffmpeg-${process.pid}.exe`) }
		);
		drain(built.resource.playStream);
		await within(5000, new Promise((resolve) => built.resource.playStream.once('end', resolve)), 'stream end');
		assert.strictEqual(built.resource.ended, true);
		built.kill();
	} finally {
		console.error = original;
	}
	const logged = lines.join('\n');
	assert.match(logged, /part 101/);
	assert.ok(!logged.includes(TOKEN));
});
